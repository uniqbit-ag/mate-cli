import { describe, expect, test } from "claude-code/testing";
import type { Engine } from "claude-code/testing";
import type { PromptAutocompleteInput, PromptAutocompleteResult } from "claude-code";
import { RULES, policyJson } from "./policy.ts";
import { world } from "./world.ts";

// Which companion a session gets, and when the mod holds back: seen through
// the file a mention reads and the rows the `@` menu gains. Each test has a
// companion of its own, so none sees a file list the mod kept for another.

const POLICY = policyJson();

async function mentionNote($: Engine, rel: string): Promise<string | undefined> {
  const result = await $.prompt.mention({ mention: `mate:${rel}`, path: `/work/x/mate:${rel}` });
  return result.context?.[0];
}

/** The kit raises prompt.autocomplete like any engine event, but its typings leave it off `$.prompt`. */
type Autocompleting = {
  autocomplete: (e: PromptAutocompleteInput) => Promise<PromptAutocompleteResult>;
};

async function rows($: Engine, token: string): Promise<string[]> {
  const result = await ($.prompt as unknown as Autocompleting).autocomplete({
    text: token,
    cursor: token.length,
    token,
    start: 0,
  });
  return result.suggestions.map((row) => row.text);
}

const projection = (path: string) =>
  `# generated by mate — do not edit\nMATE_PROJECTION_STAMP='1'\nMATE_ARTIFACT_PATH='${path}'\n`;

describe("the companion", () => {
  test("is $MATE_ARTIFACT_PATH, as its real path", async ($, on) => {
    const { reads } = world(on, {
      sessionRoot: "/work/env",
      env: { MATE_ARTIFACT_PATH: "/links/companion", MATE_POLICY_JSON: POLICY },
      disk: { "/links/companion": { link: "/real/companion" }, "/real/companion/a.md": "a" },
    });
    await mentionNote($, "a.md");
    expect(reads.map((read) => read.path)).toEqual(["/real/companion/a.md"]);
  });

  test("is none without $MATE_ARTIFACT_PATH, and a mention names mate claude", async ($, on) => {
    const { reads, runs } = world(on, { sessionRoot: "/work/plain" });
    expect(await rows($, "@mate:")).toEqual([]);
    const note = await mentionNote($, "AGENTS.md");
    expect(note).toContain("no mate companion");
    expect(note).toContain("`mate claude`");
    expect(reads).toEqual([]);
    expect(runs).toEqual([]);
  });

  test("is not found through a projection in the working repo", async ($, on) => {
    const { reads } = world(on, {
      sessionRoot: "/work/proj/packages/app",
      env: { MATE_POLICY_JSON: POLICY },
      disk: {
        "/work/proj/.mate/config/registry.yaml": "repos: {}",
        "/work/proj/.mate/projection.env": projection("/companions/proj"),
        "/work/proj/.mate/companion": { link: "/companions/proj" },
        "/companions/proj/a.md": "a",
      },
    });
    expect(await mentionNote($, "a.md")).toContain("no mate companion");
    expect(reads).toEqual([]);
  });

  test("is none when $MATE_ARTIFACT_PATH is not an absolute path", async ($, on) => {
    const { reads } = world(on, {
      sessionRoot: "/work/rel",
      env: { MATE_ARTIFACT_PATH: "companion", MATE_POLICY_JSON: POLICY },
      disk: { "/work/rel/companion/a.md": "a" },
    });
    expect(await mentionNote($, "a.md")).toContain("no mate companion");
    expect(reads).toEqual([]);
  });

  test("is none when $MATE_ARTIFACT_PATH names a file", async ($, on) => {
    const { reads } = world(on, {
      env: { MATE_ARTIFACT_PATH: "/files/notes.md", MATE_POLICY_JSON: POLICY },
      disk: { "/files/notes.md": "notes" },
    });
    expect(await rows($, "@mate:")).toEqual([]);
    expect(await mentionNote($, "a.md")).toContain("no mate companion");
    expect(reads).toEqual([]);
  });
});

describe("a session inside the companion", () => {
  test("gains no rows, since Claude's own rows list those files", async ($, on) => {
    const { runs } = world(on, {
      sessionRoot: "/c/inside/openspec",
      env: { MATE_ARTIFACT_PATH: "/c/inside", MATE_POLICY_JSON: POLICY },
      disk: { "/c/inside/openspec": null, "/c/inside/AGENTS.md": "agents" },
      git: { "/c/inside": { files: ["AGENTS.md"] } },
    });
    expect(await rows($, "@mate:")).toEqual([]);
    expect(await rows($, "@ma")).toEqual([]);
    expect(runs).toEqual([]);
  });

  test("gains no rows when its root links into the companion", async ($, on) => {
    world(on, {
      sessionRoot: "/links/inside",
      env: { MATE_ARTIFACT_PATH: "/c/linked", MATE_POLICY_JSON: POLICY },
      disk: { "/links/inside": { link: "/c/linked" }, "/c/linked/AGENTS.md": "agents" },
      git: { "/c/linked": { files: ["AGENTS.md"] } },
    });
    expect(await rows($, "@mate:")).toEqual([]);
  });

  test("still attaches a typed mention", async ($, on) => {
    const { reads } = world(on, {
      sessionRoot: "/c/typed",
      env: { MATE_ARTIFACT_PATH: "/c/typed", MATE_POLICY_JSON: POLICY },
      disk: { "/c/typed/AGENTS.md": "agents" },
    });
    await mentionNote($, "AGENTS.md");
    expect(reads.map((read) => read.path)).toEqual(["/c/typed/AGENTS.md"]);
  });
});

describe("without a readable secret policy", () => {
  const brokenRule = { ...RULES[".env"], source: "^[.env$" };
  const cases: { name: string; json: string | undefined; cause: string }[] = [
    { name: "unset", json: undefined, cause: "is not set" },
    { name: "older", json: '{"allowedAgents":["claude"]}', cause: "holds no secret policy" },
    {
      name: "broken",
      json: JSON.stringify({ secrets: { guardrails: true, deny: [brokenRule], allow: [] } }),
      cause: "does not compile",
    },
  ];

  for (const { name, json, cause } of cases) {
    test(`(${name}) no rows appear and every mention says why`, async ($, on) => {
      const root = `/c/policy-${name}`;
      const { reads, runs } = world(on, {
        env: {
          MATE_ARTIFACT_PATH: root,
          ...(json === undefined ? {} : { MATE_POLICY_JSON: json }),
        },
        disk: { [`${root}/AGENTS.md`]: "agents" },
        git: { [root]: { files: ["AGENTS.md"] } },
      });
      expect(await rows($, "@mate:")).toEqual([]);
      expect(await rows($, "@ag")).toEqual([]);
      for (const rel of ["AGENTS.md", "missing.md"]) {
        const note = await mentionNote($, rel);
        expect(note).toContain(cause);
        expect(note).toContain("mate version");
      }
      expect(reads).toEqual([]);
      expect(runs).toEqual([]);
    });
  }
});
