import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";

import { runOpenSpec } from "../../lib/openspec-cli";

/** OpenSpec workflow → the Mate skill that carries it as `references/<workflow>.md`. */
export const VENDORED_WORKFLOWS = [
  { workflow: "openspec-explore", skill: "mate-explore-change" },
  { workflow: "openspec-propose", skill: "mate-propose-change" },
  { workflow: "openspec-apply-change", skill: "mate-apply-change" },
  { workflow: "openspec-update-change", skill: "mate-propose-change" },
] as const;

/** OpenSpec tools whose generated text is vendored, each into the Mate skill bucket of the same name. */
const TOOLS = ["claude", "agents"] as const;

/** `/opsx:<command>` and `/openspec-<workflow>` → the Mate skill that replaces both. */
const COMMAND_REWRITES: Record<string, string> = {
  "/opsx:explore": "/mate-explore-change",
  "/openspec-explore": "/mate-explore-change",
  "/opsx:propose": "/mate-propose-change",
  "/openspec-propose": "/mate-propose-change",
  "/opsx:apply": "/mate-apply-change",
  "/openspec-apply-change": "/mate-apply-change",
  "/opsx:archive": "/mate-archive-change",
  "/openspec-archive-change": "/mate-archive-change",
  "/opsx:update": "/mate-propose-change",
  "/openspec-update-change": "/mate-propose-change",
};

/** A slash command, not a path segment such as `references/openspec-explore.md`. */
const COMMAND_REFERENCE = /(?<![\w.-])\/(?:opsx:|openspec-)[a-z][a-z-]*[a-z]/g;
const FRONTMATTER = /^---\r?\n[\s\S]*?\r?\n---(?:\r?\n)+/;

export const NOTICES_FILE = "THIRD-PARTY-NOTICES.md";

/** Every `/opsx:` or `/openspec-` command reference in `text`, in order. */
export function findCommandReferences(text: string): string[] {
  return text.match(COMMAND_REFERENCE) ?? [];
}

/** Rewrites mapped command references; bare `openspec <command>` CLI calls stay. */
export function rewriteCommandReferences(text: string): string {
  return text.replace(COMMAND_REFERENCE, (reference) => COMMAND_REWRITES[reference] ?? reference);
}

/** Path below `mate-skills/` of a vendored reference file. */
function referencePath(
  tool: (typeof TOOLS)[number],
  { workflow, skill }: (typeof VENDORED_WORKFLOWS)[number],
): string {
  return `${tool}/${skill}/references/${workflow}.md`;
}

async function readPackageFile(cliPath: string, file: string): Promise<string> {
  return fs.readFile(path.resolve(path.dirname(cliPath), "..", file), "utf8");
}

async function readVersion(cliPath: string): Promise<string> {
  return (JSON.parse(await readPackageFile(cliPath, "package.json")) as { version: string })
    .version;
}

function header(workflow: string, tool: string, version: string): string {
  return [
    `<!-- Vendored from OpenSpec ${version}: the \`${workflow}\` workflow its \`${tool}\` tool generates.`,
    "     Copyright (c) OpenSpec Contributors, MIT License (see THIRD-PARTY-NOTICES.md in Mate).",
    "     Regenerated by `bun run vendor:openspec`; do not edit. -->",
    "",
    "",
  ].join("\n");
}

/**
 * Each vendored reference file, keyed by its path below `mate-skills/`, rendered from
 * the OpenSpec CLI at `cliPath`. Throws on a missing skill, missing frontmatter, or a
 * command reference no rewrite rule maps, so no partial output is ever written.
 */
export async function renderOpenSpecReferences(cliPath: string): Promise<Map<string, string>> {
  const version = await readVersion(cliPath);
  const workdir = await fs.mkdtemp(path.join(os.tmpdir(), "mate-vendor-openspec-"));
  try {
    const init = await runOpenSpec(["init", "--tools", TOOLS.join(","), workdir], {
      cwd: workdir,
      bin: cliPath,
    });
    if (init.code !== 0) {
      throw new Error(`openspec init exited with code ${init.code}: ${init.stderr.trim()}`);
    }

    const files = new Map<string, string>();
    for (const tool of TOOLS) {
      for (const vendored of VENDORED_WORKFLOWS) {
        const { workflow } = vendored;
        const generated = path.join(workdir, `.${tool}`, "skills", workflow, "SKILL.md");
        const source = await fs.readFile(generated, "utf8");
        if (!FRONTMATTER.test(source)) {
          throw new Error(`OpenSpec ${workflow} (${tool}) has no skill frontmatter to strip.`);
        }
        const body = rewriteCommandReferences(source.replace(FRONTMATTER, ""));
        const unmapped = findCommandReferences(body);
        if (unmapped.length > 0) {
          throw new Error(
            `OpenSpec ${workflow} (${tool}) references commands with no Mate rewrite: ${[...new Set(unmapped)].join(", ")}`,
          );
        }
        files.set(referencePath(tool, vendored), header(workflow, tool, version) + body);
      }
    }
    return files;
  } finally {
    await fs.rm(workdir, { recursive: true, force: true });
  }
}

/** The notices file for the vendored text, carrying the bundled package's `LICENSE` verbatim. */
export async function renderOpenSpecNotices(cliPath: string): Promise<string> {
  const version = await readVersion(cliPath);
  const license = await readPackageFile(cliPath, "LICENSE");
  const vendored = TOOLS.flatMap((tool) =>
    VENDORED_WORKFLOWS.map((workflow) => `- \`${referencePath(tool, workflow)}\``),
  );
  return [
    "# Third-Party Notices",
    "",
    `The following files contain workflow text from OpenSpec ${version}`,
    "(https://github.com/Fission-AI/OpenSpec), with command references rewritten to",
    "the matching Mate skills:",
    "",
    ...vendored,
    "",
    "OpenSpec is distributed under this license:",
    "",
    "```text",
    license.trimEnd(),
    "```",
    "",
  ].join("\n");
}
