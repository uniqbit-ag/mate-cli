import { getActiveDistribution } from "../distribution";
import { FRAMEWORK_NAME } from "../framework";
import { pluginCliCommandLines } from "./plugin-commands";

export function usage(): string {
  const n = FRAMEWORK_NAME;
  const packageName =
    getActiveDistribution().config.update?.packageName ?? `@uniqbit/${FRAMEWORK_NAME}`;
  return [
    `Mate CLI (${packageName})`,
    "",
    "Commands:",
    ` ${n} install [--yes] [--frozen-plugins]`,
    ` ${n} companion link`,
    ` ${n} companion setup`,
    ` ${n} companion register [path]`,
    ` ${n} companion prepare --from <bundle> [path]`,
    ` ${n} companion list`,
    ` ${n} companion sync`,
    ` ${n} companion update [--yes]`,
    ` ${n} companion open`,
    ` ${n} companion tui`,
    ` ${n} working cleanup`,
    ` ${n} working link --companion <path> --yes`,
    ` ${n} working worktree <workset-id> [--companion <path>] [--no-install] [--json]`,
    ` ${n} working worktree --change <change> [--enter] [--companion <path>] [--no-install] [--json]`,
    ` ${n} working worktree prune [--companion <path>] [--json]`,
    ` ${n} wrap [--companion PATH]`,
    ` ${n} unwrap`,
    ` ${n} session prepare --repo <dir> [--json] [--sync]`,
    ` ${n} session context --repo <dir> [--json]`,
    ` ${n} session add --runtime <claude|opencode> --id <id> --cwd <dir> --json`,
    ` ${n} session list --json`,
    ` ${n} session remove <id> --json`,
    ` ${n} session stop <id> --json`,
    ` ${n} hub init [folder]`,
    ` ${n} hub add [source] [--id ID] [--path PATH]`,
    ` ${n} hub sync [--json] (companions + hub plugins)`,
    ` ${n} artifact publish <anchor|change-name> [--type openspec] [--no-push] [--json]`,
    "   target: a dated archive anchor, or a change name matching exactly one archive",
    ` ${n} artifact pending [--json]`,
    ` ${n} artifact link <change>... [--repository <org/repo>] [--branch <b> [--direct]]`,
    "   [--not-applicable <reason>] [--pr <url>] [--ticket <KEY>] [--refresh]",
    "   [--confirm-merged|--confirm-open|--confirm-dropped] [--json]",
    ` ${n} artifact archive <change> [--repository <org/repo>] [--branch <b> [--direct]|--not-applicable <reason>|--skip-branch] [--json]`,
    ` ${n} artifact apply-context <change> --json [--since <digest>]`,
    ` ${n} doctor`,
    ` ${n} report [--days N] [--input FILE|-] [--json]`,
    ` ${n} studio [--writable] [--terminal] [--detach-timeout <minutes>]`,
    ` ${n} studio serve --port <port> [--host <host>] [--writable] [--terminal]`,
    "   [--detach-timeout <minutes>] [--token <value>] [--allowed-host <host>]",
    "   [--public-origin <origin>] [--companion <path>] [--no-git]",
    "   [--profile standard|appliance]",
    ` ${n} factory serve --socket <path> --docker-host <url> --state-dir <dir> --image <image>`,
    "   --user <name> --companions-dir <dir> (the appliance's factory broker, run as root)",
    ` ${n} factory attach <workset> --session <id> --companion <path> [--start clarify|explore|continue]`,
    ` ${n} config`,
    ` ${n} vscode setup [--editor code|cursor] [--vsix <path>] [--if-installed]`,
    ` ${n} claude [args...] (after --: --no-git, --companion, --yes no-op)`,
    ` ${n} opencode [args...] (after --: --no-git, --companion, --yes no-op)`,
    ` ${n} cap openspec <subcommand> [args...]`,
    ` ${n} cap graphify <subcommand> [args...]`,
    ` ${n} cap index [--graphify] [--tokensave]`,
    ` ${n} plugin install <package>[@version]`,
    ...pluginCliCommandLines(),
    ` ${n} update`,
    ` ${n} update --check`,
    "",
    "Working repository state:",
    " linked repositories locally exclude root .claude/, .opencode/, and .agents/ directories",
    ` ${n} working cleanup removes Mate-owned local integration without resetting product work`,
    " tracked files and capability data remain untouched; link or launch recreates required state",
    "",
    "Wrapped repositories:",
    ` ${n} wrap configures the repository so sessions you start yourself load the companion`,
    ` ${n} claude does not run while a repository is wrapped for Claude`,
    ` ${n} opencode wraps the repository for OpenCode itself, then starts plain \`opencode\``,
    ` ${n} unwrap withdraws the wrap and restores managed launches; the link is kept`,
    "",
    "Doctor states:",
    " linked-working-repository — cwd is inside a registered working repository",
    " companion-repository — cwd is the companion repository itself",
    " not-linked — cwd is not linked to any companion",
    "",
  ].join("\n");
}
