import { getActiveDistribution } from "../../../distribution";
import { FRAMEWORK_NAME } from "../../../framework";
import { audiencePluginPackages } from "../dynamic-plugins/audiences";
import {
  LOCAL_PLUGINS_FILE_GITIGNORE_ENTRY,
  LOCAL_PLUGINS_WORKSPACE_GITIGNORE_ENTRY,
  PLUGIN_AUDIENCE_NPMRC_GITIGNORE_ENTRY,
  PLUGIN_LOCAL_OVERRIDES_GITIGNORE_ENTRY,
  PLUGIN_WORKSPACE_NPMRC_GITIGNORE_ENTRY,
} from "../dynamic-plugins/paths";
import type { Plugin, SetupContext } from "../plugin";

const MANAGED_START = (name: string) => `# ${name} managed: start`;
const MANAGED_END = (name: string) => `# ${name} managed: end`;

// Legacy per-feature markers — stripped on next sync so old files self-heal
const LEGACY_MARKERS: [string, string][] = [
  ["# mate managed: uv start", "# mate managed: uv end"],
  ["# mate managed: headroom start", "# mate managed: headroom end"],
];

function stripManagedBlock(content: string, start: string, end: string): string {
  const startIndex = content.indexOf(start);
  if (startIndex === -1) return content;

  const endIndex = content.indexOf(end, startIndex);
  const blockEnd = endIndex === -1 ? content.length : endIndex + end.length;
  const before = content.slice(0, startIndex).trimEnd();
  const after = content.slice(blockEnd).trimStart();
  const merged = [before, after].filter(Boolean).join("\n\n");
  return merged ? `${merged}\n` : "";
}

function appendManagedBlock(content: string, frameworkName: string, entries: string[]): string {
  const block = [MANAGED_START(frameworkName), ...entries, MANAGED_END(frameworkName)].join("\n");
  const kept = content.trimEnd();
  return kept ? `${kept}\n\n${block}\n` : `${block}\n`;
}

export async function writeManagedGitignoreBlock(
  gitignorePath: string,
  frameworkName: string,
  entries: string[],
): Promise<void> {
  const { readFile, writeFile } = await import("node:fs/promises");

  const start = MANAGED_START(frameworkName);
  const end = MANAGED_END(frameworkName);

  let existing = "";
  try {
    existing = await readFile(gitignorePath, "utf8");
  } catch {
    /* absent is fine */
  }

  let content = stripManagedBlock(existing, start, end);
  for (const [s, e] of LEGACY_MARKERS) {
    content = stripManagedBlock(content, s, e);
  }

  if (entries.length > 0) content = appendManagedBlock(content, frameworkName, entries);

  if (content !== existing) {
    await writeFile(gitignorePath, content, "utf8");
  }
}

/**
 * Adds `entries` the file does not list yet, inside the managed block when it
 * has one. Every other line stays where it is.
 */
export async function addManagedGitignoreEntries(
  gitignorePath: string,
  entries: string[],
): Promise<void> {
  const { readFile, writeFile } = await import("node:fs/promises");
  const existing = await readFile(gitignorePath, "utf8").catch(() => "");
  const lines = existing.split("\n");
  const missing = entries.filter((entry) => !lines.includes(entry));
  if (missing.length === 0) return;

  const start = lines.indexOf(MANAGED_START(FRAMEWORK_NAME));
  const end = start === -1 ? -1 : lines.indexOf(MANAGED_END(FRAMEWORK_NAME), start);
  if (end !== -1) {
    lines.splice(end, 0, ...missing);
    await writeFile(gitignorePath, lines.join("\n"), "utf8");
    return;
  }
  // A start marker without an end is left for the next setup to repair.
  await writeFile(gitignorePath, appendManagedBlock(existing, FRAMEWORK_NAME, missing), "utf8");
}

export function collectManagedGitignoreEntries(ctx: SetupContext, plugins: Plugin[]): string[] {
  // Baseline for every companion: node_modules never versions wherever a tool
  // materializes it, and the machine-local distribution-dependencies workspace
  // (.mate/plugins/.local/ — context-mode, future consumers) is regenerated by
  // setup/install in full — version pins live in .mate/config and in code,
  // never in the tree itself. This is distinct from the committed dynamic-
  // plugins workspace at .mate/plugins/, whose package.json and lockfile stay
  // trackable.
  const entries = [
    "node_modules/",
    `.${FRAMEWORK_NAME}/plugins/.local/`,
    // Holds absolute local paths of every linked working repo; never shared
    // across machines or committed to the companion repo.
    `.${FRAMEWORK_NAME}/config/registry.yaml`,
    ".mcp.json.bak",
    // Listed before a member's first local plugin, so that one never shows in `git status`.
    LOCAL_PLUGINS_FILE_GITIGNORE_ENTRY,
    LOCAL_PLUGINS_WORKSPACE_GITIGNORE_ENTRY,
    ...plugins
      .filter((p) => p.kind !== "root" && (p.isEnabled(ctx.config) || p.persistGitignoreEntries))
      .flatMap((p) => p.gitignoreEntries?.(ctx) ?? []),
  ];
  // Dynamic-plugin loading artifacts: the local override file and the local
  // registry credentials (the shared workspace's file and its link in every
  // audience workspace) never version. A workspace's installed tree
  // (node_modules) is already covered by the baseline node_modules/ rule
  // above, since the workspaces live outside the dependencies tree wildcard;
  // each package.json and committed package-lock.json is the
  // pin/reproducibility record and is never touched by any ignore rule.
  if (ctx.config.plugins?.length || audiencePluginPackages(ctx.config).size > 0) {
    entries.push(
      PLUGIN_WORKSPACE_NPMRC_GITIGNORE_ENTRY,
      PLUGIN_AUDIENCE_NPMRC_GITIGNORE_ENTRY,
      PLUGIN_LOCAL_OVERRIDES_GITIGNORE_ENTRY,
    );
  }
  return entries;
}

export function createGitignorePlugin(
  frameworkName: string | (() => string),
  allPlugins?: () => Plugin[],
): Plugin {
  // Resolve lazily so plugin sets can be built before a distribution is active.
  const resolveName = typeof frameworkName === "function" ? frameworkName : () => frameworkName;
  const resolvePlugins = allPlugins ?? (() => getActiveDistribution().registry.getAll());
  return {
    id: "gitignore",
    kind: "root",
    label: "Gitignore",
    description: "Maintain the managed gitignore block from all active plugin contributions.",
    defaultSelected: true,
    isEnabled: () => true,
    async apply(ctx: SetupContext) {
      const { join } = await import("node:path");
      const entries = collectManagedGitignoreEntries(ctx, resolvePlugins());

      await writeManagedGitignoreBlock(
        join(ctx.companionPath, ".gitignore"),
        resolveName(),
        entries,
      );
    },
    async teardown(ctx: SetupContext) {
      const { join } = await import("node:path");
      await writeManagedGitignoreBlock(join(ctx.companionPath, ".gitignore"), resolveName(), []);
    },
  };
}
