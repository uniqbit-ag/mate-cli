import { describe, expect, test } from "claude-code/testing";
import type { Engine } from "claude-code/testing";
import type { PromptAutocompleteInput, PromptAutocompleteResult } from "claude-code";
import { RULES, contextReply, policyJson } from "./policy.ts";
import { LAUNCHER, world, type MateAnswer } from "./world.ts";

/** Each test has its own session folder and companion, so none sees what the mod kept for another. */

const POLICY = policyJson();

async function mentionNote($: Engine, rel: string): Promise<string | undefined> {
  const result = await $.prompt.mention({ mention: `mate:${rel}`, path: `/work/x/mate:${rel}` });
  return result.context?.[0];
}

/** The kit raises prompt.autocomplete like any engine event, but its typings leave it off `$.prompt`. */
type Autocompleting = {
  autocomplete: (e: PromptAutocompleteInput) => Promise<PromptAutocompleteResult>;
};

async function suggestions(
  $: Engine,
  token: string,
): Promise<PromptAutocompleteResult["suggestions"]> {
  const result = await ($.prompt as unknown as Autocompleting).autocomplete({
    text: token,
    cursor: token.length,
    token,
    start: 0,
  });
  return result.suggestions;
}

async function rows($: Engine, token: string): Promise<string[]> {
  return (await suggestions($, token)).map((row) => row.text);
}

const projection = (path: string) =>
  `# generated by mate — do not edit\nMATE_PROJECTION_STAMP='1'\nMATE_ARTIFACT_PATH='${path}'\n`;

const answers = (root: string, deny: string[] = []): MateAnswer => ({
  stdout: contextReply(root, { deny }),
});

const refusal = (code: string, message = "refused"): MateAnswer => ({
  stdout: JSON.stringify({ protocol: 1, error: { code, message } }),
  exitCode: 1,
});

describe("a session started by mate claude", () => {
  test("uses $MATE_ARTIFACT_PATH, as its real path", async ($, on) => {
    const { reads, mateRuns } = world(on, {
      sessionRoot: "/work/env",
      env: { MATE_ARTIFACT_PATH: "/links/companion", MATE_POLICY_JSON: POLICY },
      disk: { "/links/companion": { link: "/real/companion" }, "/real/companion/a.md": "a" },
    });
    await mentionNote($, "a.md");
    expect(reads.map((read) => read.path)).toEqual(["/real/companion/a.md"]);
    expect(mateRuns).toEqual([]);
  });

  test("lists the launch's companion even when Mate names another", async ($, on) => {
    const { mateRuns } = world(on, {
      sessionRoot: "/work/launch-wins",
      env: { MATE_ARTIFACT_PATH: "/c/launch-acme", MATE_POLICY_JSON: POLICY },
      disk: { "/c/launch-acme/acme.md": "a", "/c/launch-other/other.md": "o" },
      git: {
        "/c/launch-acme": { files: ["acme.md"] },
        "/c/launch-other": { files: ["other.md"] },
      },
      mate: { "/work/launch-wins": answers("/c/launch-other") },
    });
    expect(await rows($, "@mate:")).toEqual(["@mate:acme.md "]);
    expect(mateRuns).toEqual([]);
  });

  test("has no companion when $MATE_ARTIFACT_PATH is not an absolute path", async ($, on) => {
    const { reads, mateRuns } = world(on, {
      sessionRoot: "/work/rel",
      env: { MATE_ARTIFACT_PATH: "companion", MATE_POLICY_JSON: POLICY },
      disk: { "/work/rel/companion/a.md": "a", "/c/rel/a.md": "a" },
      mate: { "/work/rel": answers("/c/rel") },
    });
    expect(await mentionNote($, "a.md")).toContain("no mate companion");
    expect(reads).toEqual([]);
    expect(mateRuns).toEqual([]);
  });

  test("has no companion when $MATE_ARTIFACT_PATH names a file, without asking Mate", async ($, on) => {
    const { reads, mateRuns } = world(on, {
      sessionRoot: "/work/file",
      env: { MATE_ARTIFACT_PATH: "/files/notes.md", MATE_POLICY_JSON: POLICY },
      disk: { "/files/notes.md": "notes", "/c/file/a.md": "a" },
      git: { "/c/file": { files: ["a.md"] } },
      mate: { "/work/file": answers("/c/file") },
    });
    expect(await rows($, "@mate:")).toEqual([]);
    expect(await mentionNote($, "a.md")).toContain("no mate companion");
    expect(reads).toEqual([]);
    expect(mateRuns).toEqual([]);
  });
});

describe("a plain session", () => {
  test("lists the companion Mate names, described as a mate companion", async ($, on) => {
    world(on, {
      sessionRoot: "/work/plain-rows",
      disk: { "/c/plain-acme/AGENTS.md": "agents" },
      git: { "/c/plain-acme": { files: ["AGENTS.md"] } },
      mate: { "/work/plain-rows": answers("/c/plain-acme") },
    });
    const found = await suggestions($, "@mate:");
    expect(found.map((row) => row.text)).toEqual(["@mate:AGENTS.md "]);
    expect(found[0]?.description).toBe("plain-acme (mate companion)");
  });

  test("runs Mate's launcher in the Mate home for the session folder, with a 5-second limit", async ($, on) => {
    const { mateRuns } = world(on, {
      sessionRoot: "/work/plain-argv",
      disk: { "/c/plain-argv/a.md": "a" },
      mate: { "/work/plain-argv": answers("/c/plain-argv") },
    });
    await mentionNote($, "a.md");
    /** Never in the session folder, whose `bunfig.toml` preload Bun would run inside Mate's answer. */
    expect(mateRuns).toEqual([
      {
        argv: [LAUNCHER, "session", "context", "--repo", "/work/plain-argv", "--json"],
        cwd: "/home/me/.mate/runtime/bin",
        timeoutMs: 5000,
      },
    ]);
  });

  test("does not ask Mate for a session folder that is not an absolute path", async ($, on) => {
    const { mateRuns } = world(on, {
      sessionRoot: "work/relative",
      mate: { "work/relative": answers("/c/relative") },
    });
    expect(await mentionNote($, "a.md")).toContain("absolute");
    expect(mateRuns).toEqual([]);
  });

  test("attaches from the companion Mate names, as its real path", async ($, on) => {
    const { reads } = world(on, {
      sessionRoot: "/work/plain-real",
      disk: { "/links/plain-real": { link: "/c/plain-real" }, "/c/plain-real/a.md": "a" },
      mate: { "/work/plain-real": answers("/links/plain-real") },
    });
    await mentionNote($, "a.md");
    expect(reads.map((read) => read.path)).toEqual(["/c/plain-real/a.md"]);
  });

  test("in a wrapped worktree lists the companion Mate names for it", async ($, on) => {
    const { mateRuns } = world(on, {
      sessionRoot: "/work/wt-app/.worktrees/feature",
      disk: { "/c/wt-acme/AGENTS.md": "agents" },
      git: { "/c/wt-acme": { files: ["AGENTS.md"] } },
      mate: { "/work/wt-app/.worktrees/feature": answers("/c/wt-acme") },
    });
    expect(await rows($, "@mate:")).toEqual(["@mate:AGENTS.md "]);
    expect(mateRuns[0]?.argv).toContain("/work/wt-app/.worktrees/feature");
  });

  test("does not search the working repo for a projection", async ($, on) => {
    const { reads, mateRuns } = world(on, {
      sessionRoot: "/work/proj/packages/app",
      disk: {
        "/work/proj/.mate/config/registry.yaml": "repos: {}",
        "/work/proj/.mate/projection.env": projection("/companions/proj"),
        "/work/proj/.mate/companion": { link: "/companions/proj" },
        "/companions/proj/a.md": "a",
      },
    });
    const note = await mentionNote($, "a.md");
    expect(note).toContain("no mate companion");
    expect(note).toContain("`mate doctor`");
    expect(reads).toEqual([]);
    expect(mateRuns).toHaveLength(1);
  });

  test("hides rows inside the companion Mate names, and still attaches a typed mention", async ($, on) => {
    const { reads } = world(on, {
      sessionRoot: "/c/plain-inside/openspec",
      disk: { "/c/plain-inside/openspec": null, "/c/plain-inside/AGENTS.md": "agents" },
      git: { "/c/plain-inside": { files: ["AGENTS.md"] } },
      mate: { "/c/plain-inside/openspec": answers("/c/plain-inside") },
    });
    expect(await rows($, "@mate:")).toEqual([]);
    await mentionNote($, "AGENTS.md");
    expect(reads.map((read) => read.path)).toEqual(["/c/plain-inside/AGENTS.md"]);
  });

  test("has no companion when the folder Mate names is gone", async ($, on) => {
    const { reads } = world(on, {
      sessionRoot: "/work/plain-gone",
      mate: { "/work/plain-gone": answers("/c/plain-gone") },
    });
    expect(await rows($, "@mate:")).toEqual([]);
    expect(await mentionNote($, "a.md")).toContain("no mate companion");
    expect(reads).toEqual([]);
  });
});

describe("Mate's answer in a plain session", () => {
  test("serves the menu once per 30 seconds", async ($, on) => {
    const { mateRuns, clock } = world(on, {
      sessionRoot: "/work/ask-once",
      disk: { "/c/ask-once/openspec.md": "o" },
      git: { "/c/ask-once": { files: ["openspec.md"] } },
      mate: { "/work/ask-once": answers("/c/ask-once") },
    });
    for (const token of ["@mate:o", "@mate:op", "@mate:ope"]) await rows($, token);
    expect(mateRuns).toHaveLength(1);
    await clock.advance(30_000);
    await rows($, "@mate:open");
    expect(mateRuns).toHaveLength(2);
  });

  test("is asked once by keystrokes that overlap its answer", async ($, on) => {
    const { mateRuns } = world(on, {
      sessionRoot: "/work/ask-overlap",
      disk: { "/c/ask-overlap/openspec.md": "o" },
      git: { "/c/ask-overlap": { files: ["openspec.md"] } },
      mate: { "/work/ask-overlap": answers("/c/ask-overlap") },
    });
    await Promise.all(["@mate:o", "@mate:op", "@mate:ope"].map((token) => rows($, token)));
    expect(mateRuns).toHaveLength(1);
  });

  test("keeps a failure for the window instead of asking on every keystroke", async ($, on) => {
    const { mateRuns, clock } = world(on, {
      sessionRoot: "/work/ask-timeout",
      mate: { "/work/ask-timeout": "timeout" },
    });
    await rows($, "@mate:o");
    await rows($, "@mate:op");
    await clock.advance(20_000);
    expect(await rows($, "@mate:ope")).toEqual([]);
    expect(mateRuns).toHaveLength(1);
  });

  test("is asked anew by each sent mention", async ($, on) => {
    const { mateRuns, reads, clock } = world(on, {
      sessionRoot: "/work/ask-mention",
      disk: { "/c/ask-mention/AGENTS.md": "agents" },
      git: { "/c/ask-mention": { files: ["AGENTS.md"] } },
      mate: { "/work/ask-mention": answers("/c/ask-mention") },
    });
    await rows($, "@mate:");
    await clock.advance(10_000);
    await mentionNote($, "AGENTS.md");
    await mentionNote($, "AGENTS.md");
    expect(mateRuns).toHaveLength(3);
    expect(reads.map((read) => read.path)).toEqual([
      "/c/ask-mention/AGENTS.md",
      "/c/ask-mention/AGENTS.md",
    ]);
  });

  test("of a failed mention is not replaced by the menu's", async ($, on) => {
    const { mate, reads } = world(on, {
      sessionRoot: "/work/ask-fails",
      disk: { "/c/ask-fails/AGENTS.md": "agents" },
      git: { "/c/ask-fails": { files: ["AGENTS.md"] } },
      mate: { "/work/ask-fails": answers("/c/ask-fails") },
    });
    expect(await rows($, "@mate:")).toEqual(["@mate:AGENTS.md "]);
    mate["/work/ask-fails"] = "missing";
    const note = await mentionNote($, "AGENTS.md");
    expect(note).toContain("could not run");
    expect(reads).toEqual([]);
  });

  test("brings a changed companion to the menu within 30 seconds", async ($, on) => {
    const { mate, clock } = world(on, {
      sessionRoot: "/work/ask-moved",
      disk: { "/c/moved-acme/acme.md": "a", "/c/moved-other/other.md": "o" },
      git: {
        "/c/moved-acme": { files: ["acme.md"] },
        "/c/moved-other": { files: ["other.md"] },
      },
      mate: { "/work/ask-moved": answers("/c/moved-acme") },
    });
    expect(await rows($, "@mate:")).toEqual(["@mate:acme.md "]);
    mate["/work/ask-moved"] = answers("/c/moved-other");
    expect(await rows($, "@mate:")).toEqual(["@mate:acme.md "]);
    await clock.advance(30_000);
    expect(await rows($, "@mate:")).toEqual(["@mate:other.md "]);
  });

  test("brings a policy change to the next mention, and to the menu within 30 seconds", async ($, on) => {
    const { mate, reads, clock } = world(on, {
      sessionRoot: "/work/ask-policy",
      disk: { "/c/ask-policy/infra/acme.tfstate": "state" },
      git: { "/c/ask-policy": { files: ["infra/acme.tfstate"] } },
      mate: { "/work/ask-policy": answers("/c/ask-policy") },
    });
    expect(await rows($, "@mate:acme")).toContain("@mate:infra/acme.tfstate ");
    await mentionNote($, "infra/acme.tfstate");
    expect(reads).toHaveLength(1);

    mate["/work/ask-policy"] = answers("/c/ask-policy", ["*.tfstate"]);
    expect(await mentionNote($, "infra/acme.tfstate")).toContain("(`*.tfstate`)");
    expect(reads).toHaveLength(1);
    await clock.advance(30_000);
    expect(await rows($, "@mate:acme")).not.toContain("@mate:infra/acme.tfstate ");
  });
});

describe("when Mate gives no context", () => {
  const cases: { name: string; answer: MateAnswer; cause: string[] }[] = [
    {
      name: "not wrapped",
      answer: refusal("not-wrapped"),
      cause: ["no mate companion", "`mate doctor`"],
    },
    {
      name: "companion missing",
      answer: refusal("companion-missing"),
      cause: ["no mate companion"],
    },
    {
      name: "a companion that is not registered",
      answer: refusal("companion-not-registered", "/c/x is not registered."),
      cause: ["mate refused the companion", "companion-not-registered", "/c/x is not registered"],
    },
    {
      name: "a companion that does not link the repository",
      answer: refusal("repository-not-linked"),
      cause: ["mate refused the companion", "repository-not-linked"],
    },
    {
      name: "a missing launcher",
      answer: "missing",
      cause: [`mate's launcher ${LAUNCHER} could not run`, "mate version"],
    },
    {
      name: "a mate without the command",
      answer: { stdout: "", exitCode: 1 },
      cause: ["has no `session context` command", "mate version"],
    },
    { name: "a timeout", answer: "timeout", cause: ["did not answer within 5 seconds"] },
    {
      name: "an answer from a launcher that then fails",
      answer: { stdout: contextReply("/c/no-rules"), exitCode: 3 },
      cause: ["exited with status 3", "`mate doctor`"],
    },
    {
      name: "an unknown protocol",
      answer: { stdout: JSON.stringify({ protocol: 2, companionPath: "/c/p2" }) },
      cause: ["protocol 2", "mate version"],
    },
    {
      name: "a policy without secret rules",
      answer: {
        stdout: JSON.stringify({
          protocol: 1,
          companionPath: "/c/no-rules",
          policyJson: '{"allowedAgents":["claude"]}',
        }),
      },
      cause: ["holds no secret policy", "mate version"],
    },
  ];

  for (const { name, answer, cause } of cases) {
    test(`(${name}) no rows appear and a mention says why`, async ($, on) => {
      const sessionRoot = `/work/none-${name.replaceAll(" ", "-")}`;
      const { reads } = world(on, {
        sessionRoot,
        disk: { "/c/p2/AGENTS.md": "a", "/c/no-rules/AGENTS.md": "a" },
        git: { "/c/p2": { files: ["AGENTS.md"] }, "/c/no-rules": { files: ["AGENTS.md"] } },
        mate: { [sessionRoot]: answer },
      });
      expect(await rows($, "@mate:")).toEqual([]);
      expect(await rows($, "@ag")).toEqual([]);
      const note = await mentionNote($, "AGENTS.md");
      for (const part of cause) expect(note).toContain(part);
      expect(reads).toEqual([]);
    });
  }
});

