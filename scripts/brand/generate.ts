#!/usr/bin/env bun
/**
 * Generates every brand output from `assets/logo-kit`, the master copy of the Mate logo.
 *
 *   bun scripts/brand/generate.ts           write all outputs, including apps/docs/public/og.png
 *   bun scripts/brand/generate.ts --check   exit 1 and name each brand problem `checkBrand()` finds
 *
 * The check covers every output except `og.png`, whose bytes depend on the installed sharp
 * version. It also checks the palette against BRAND.md and scans sources for stray brand hex
 * values.
 */
import fs from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";

import { BRAND_COLORS } from "../../packages/mate-core/src/brand/palette";
import type { BrandSvgs, LogoForm, LogoSegment } from "../../packages/mate-core/src/brand/types";

const REPO_ROOT = path.resolve(import.meta.dirname, "..", "..");

const KIT = "assets/logo-kit";
const BRAND_MODULE = "packages/mate-core/src/brand";
const DOCS_BRAND = "apps/docs/public/brand";
const DOCS_COLOURS = "apps/docs/src/lib/brand.generated.ts";
const OG_IMAGE = "apps/docs/public/og.png";
const HEADER = "// Generated by scripts/brand/generate.ts from assets/logo-kit. Do not edit.";

/** Where a brand hex value would be a second source, and the files allowed to declare one. */
const HEX_SCAN_ROOTS = [
  "packages/mate-core/src",
  "packages/mate-core/opencode-plugin",
  "apps/docs/src",
  "scripts",
];
const HEX_SOURCES = [`${BRAND_MODULE}/`, DOCS_COLOURS];
const SCANNED_FILE = /\.(ts|tsx|js|mjs|css|html|astro)$/u;
const SKIPPED_DIRECTORY = new Set(["node_modules", "dist", ".astro"]);

/** The symbol is the first 14 columns of the lockup; ink cells past it belong to the wordmark. */
const SYMBOL_COLUMNS = 14;

/** The 24-bit foreground SGR parameters for a `#RRGGBB` colour, as the kit's `.ans` art writes them. */
function foregroundSgr(hex: string): string {
  const rgb = [1, 3, 5].map((offset) => Number.parseInt(hex.slice(offset, offset + 2), 16));
  return `38;2;${rgb.join(";")}`;
}

const SGR_INK = foregroundSgr(BRAND_COLORS.ink.hex);
const SGR_GREEN = foregroundSgr(BRAND_COLORS.mateGreen.hex);
const SGR_RESET = "0";

/** A file the generator owns, as a repository-relative path and its expected bytes. */
interface BrandOutput {
  path: string;
  content: Uint8Array;
}

/** Copied byte for byte from the kit into the docs site, so its pages can link them. */
const DOCS_COPIES: Record<string, string> = {
  "mate-horizontal-color.svg": "svg/mate-horizontal-color.svg",
  "mate-horizontal-on-dark.svg": "svg/mate-horizontal-on-dark.svg",
  "favicon.svg": "web/favicon.svg",
  "favicon.ico": "web/favicon.ico",
  "apple-touch-icon.png": "web/apple-touch-icon.png",
  "icon-192.png": "web/icon-192.png",
  "icon-512.png": "web/icon-512.png",
};

/** The kit file each `BRAND_SVGS` entry embeds verbatim. */
const SVG_SOURCES: Record<keyof BrandSvgs, string> = {
  symbolColor: "svg/mate-symbol-color.svg",
  symbolOnDark: "svg/mate-symbol-on-dark.svg",
  favicon: "web/favicon.svg",
};

/** `Light green` → `lightGreen`, the palette key a BRAND.md colour name maps to. */
function camelCase(name: string): string {
  const [first = "", ...rest] = name.trim().toLowerCase().split(/\s+/u);
  return first + rest.map((word) => word.charAt(0).toUpperCase() + word.slice(1)).join("");
}

/**
 * Compares the palette with the `Colour` table in BRAND.md and returns one line per missing,
 * extra, or differing colour. Throws when the table cannot be found, so a reworded BRAND.md
 * cannot pass silently.
 */
export function paletteProblems(
  brandMarkdown: string,
  palette: Record<string, { hex: string }> = BRAND_COLORS,
): string[] {
  const rows = brandMarkdown.replace(/\r\n/g, "\n").split("\n");
  const heading = rows.findIndex((row) => /^##\s+Colou?r\s*$/u.test(row));
  if (heading === -1) throw new Error("BRAND.md has no `## Colour` section");

  const table: string[] = [];
  for (const row of rows.slice(heading + 1)) {
    if (row.trim().startsWith("|")) table.push(row);
    else if (table.length > 0 || row.startsWith("#")) break;
  }
  const cells = table.map((row) =>
    row
      .trim()
      .replace(/^\||\|$/g, "")
      .split("|")
      .map((cell) => cell.trim().replace(/`/g, "")),
  );
  const header = cells[0]?.map((cell) => cell.toLowerCase());
  const nameColumn = header?.indexOf("name") ?? -1;
  const hexColumn = header?.indexOf("hex") ?? -1;
  if (nameColumn === -1 || hexColumn === -1) {
    throw new Error("BRAND.md's `Colour` section has no table with Name and HEX columns");
  }

  const problems: string[] = [];
  const seen = new Set<string>();
  for (const row of cells.slice(2)) {
    const key = camelCase(row[nameColumn] ?? "");
    const hex = row[hexColumn] ?? "";
    seen.add(key);
    const colour = palette[key];
    if (!colour) problems.push(`BRAND.md colour ${key} is missing from the palette`);
    else if (colour.hex.toLowerCase() !== hex.toLowerCase()) {
      problems.push(`BRAND.md colour ${key} is ${hex}, but the palette has ${colour.hex}`);
    }
  }
  for (const key of Object.keys(palette)) {
    if (!seen.has(key)) problems.push(`palette colour ${key} is not in BRAND.md's colour table`);
  }
  return problems;
}

/**
 * Splits one `.light.ans` row into segments. Throws on any SGR colour the kit is not known to
 * use, so a re-encoded kit fails loudly instead of producing wrong art.
 */
export function parseAnsiRow(row: string, form: LogoForm): LogoSegment[] {
  const segments: LogoSegment[] = [];
  let colour: "ink" | "green" | undefined;
  let column = 0;
  const tokens = row.match(/\x1b\[[0-9;]*m|[\s\S]/gu) ?? [];

  for (const token of tokens) {
    if (token.startsWith("\x1b[")) {
      const sgr = token.slice(2, -1);
      if (sgr === SGR_INK) colour = "ink";
      else if (sgr === SGR_GREEN) colour = "green";
      else if (sgr === SGR_RESET || sgr === "") colour = undefined;
      else throw new Error(`Unknown SGR sequence "${sgr}" in ${form} art`);
      continue;
    }

    let kind: LogoSegment["kind"];
    if (token === " ") kind = "space";
    else if (colour === "green") kind = "note";
    else if (colour === "ink") {
      kind = form === "wordmark" || column >= SYMBOL_COLUMNS ? "word" : "pane";
    } else throw new Error(`Uncoloured cell "${token}" in ${form} art`);

    const last = segments.at(-1);
    if (last?.kind === kind) last.text += token;
    else segments.push({ kind, text: token });
    column += 1;
  }

  return segments;
}

function lines(text: string): string[] {
  const rows = text.replace(/\r\n/g, "\n").split("\n");
  if (rows.at(-1) === "") rows.pop();
  return rows;
}

async function readKit(relative: string): Promise<Buffer> {
  return fs.readFile(path.join(REPO_ROOT, KIT, relative));
}

async function artModule(): Promise<string> {
  const forms = ["lockup", "symbol", "wordmark"] as const;
  const entries: string[] = [];

  for (const form of forms) {
    const block = lines((await readKit(`terminal/mate-${form}.light.ans`)).toString("utf8")).map(
      (row) => parseAnsiRow(row, form),
    );
    const ascii = lines((await readKit(`terminal/mate-${form}.ascii.txt`)).toString("utf8"));
    const columns = Math.max(
      ...block.map((row) => row.reduce((width, segment) => width + [...segment.text].length, 0)),
    );
    const rows = block.map((row) => `      ${JSON.stringify(row)},`).join("\n");
    const asciiRows = ascii.map((row) => `      ${JSON.stringify(row)},`).join("\n");
    entries.push(
      `  ${form}: {\n    block: [\n${rows}\n    ],\n    ascii: [\n${asciiRows}\n    ],\n    columns: ${columns},\n  },`,
    );
  }

  return `${HEADER}\nimport type { LogoArt, LogoForm } from "./types";\n\nexport const LOGO_ART: Record<LogoForm, LogoArt> = {\n${entries.join("\n")}\n};\n`;
}

async function svgModule(): Promise<string> {
  const entries: string[] = [];
  for (const [name, source] of Object.entries(SVG_SOURCES)) {
    const svg = (await readKit(source)).toString("utf8").trim();
    entries.push(`  ${name}: ${JSON.stringify(svg)},`);
  }
  return `${HEADER}\nimport type { BrandSvgs } from "./types";\n\nexport const BRAND_SVGS: BrandSvgs = {\n${entries.join("\n")}\n};\n`;
}

/** The palette for the docs site, which does not depend on mate-core. */
function docsColoursModule(): string {
  const entries = Object.entries(BRAND_COLORS)
    .map(([name, colour]) => `  ${name}: ${JSON.stringify(colour.hex)},`)
    .join("\n");
  return `${HEADER}\n\n/** The five Mate brand colours as hex values, from mate-core's brand palette. */\nexport const BRAND = {\n${entries}\n} as const;\n`;
}

/** Every checked output, rendered in memory from the current kit. */
async function brandOutputs(): Promise<BrandOutput[]> {
  const encode = (text: string) => new TextEncoder().encode(text);
  const outputs: BrandOutput[] = [
    { path: `${BRAND_MODULE}/art.generated.ts`, content: encode(await artModule()) },
    { path: `${BRAND_MODULE}/svg.generated.ts`, content: encode(await svgModule()) },
    { path: DOCS_COLOURS, content: encode(docsColoursModule()) },
  ];
  for (const [name, source] of Object.entries(DOCS_COPIES)) {
    outputs.push({ path: `${DOCS_BRAND}/${name}`, content: new Uint8Array(await readKit(source)) });
  }
  return outputs;
}

/** One line per brand colour that `source`, read from `relativePath`, declares as a hex value. */
export function strayHexes(
  relativePath: string,
  source: string,
  palette: Record<string, { hex: string }> = BRAND_COLORS,
): string[] {
  const lowered = source.toLowerCase();
  return Object.entries(palette)
    .filter(([, colour]) => lowered.includes(colour.hex.toLowerCase()))
    .map(([name, colour]) => `${relativePath} declares brand colour ${name} (${colour.hex})`);
}

/** Repository-relative paths of the scanned source files under `relativeDir`. */
async function scannedFiles(relativeDir: string): Promise<string[]> {
  const entries = await fs
    .readdir(path.join(REPO_ROOT, relativeDir), { withFileTypes: true })
    .catch(() => []);
  const files: string[] = [];
  for (const entry of entries) {
    const relative = `${relativeDir}/${entry.name}`;
    if (entry.isDirectory()) {
      if (!SKIPPED_DIRECTORY.has(entry.name)) files.push(...(await scannedFiles(relative)));
    } else if (SCANNED_FILE.test(entry.name)) {
      files.push(relative);
    }
  }
  return files;
}

/**
 * Every brand problem, one readable line each: the palette disagrees with BRAND.md, a generated
 * output is missing or stale, or a source file outside the brand module and the generated
 * outputs declares a brand hex value. An empty list means the brand is consistent.
 */
export async function checkBrand(): Promise<string[]> {
  const problems = paletteProblems((await readKit("BRAND.md")).toString("utf8"));

  for (const output of await brandOutputs()) {
    const current = await fs.readFile(path.join(REPO_ROOT, output.path)).catch(() => undefined);
    if (!current) problems.push(`${output.path} is missing`);
    else if (!Buffer.from(output.content).equals(current)) problems.push(`${output.path} is stale`);
  }

  const files = (await Promise.all(HEX_SCAN_ROOTS.map(scannedFiles)))
    .flat()
    .filter((file) => !HEX_SOURCES.some((allowed) => file === allowed || file.startsWith(allowed)));
  const strays = await Promise.all(
    files.map(async (file) =>
      strayHexes(file, await fs.readFile(path.join(REPO_ROOT, file), "utf8")),
    ),
  );
  problems.push(...strays.flat());

  return problems;
}

/** A 1200×630 Night canvas with the on-dark horizontal lockup centred. */
async function renderOgImage(): Promise<void> {
  const requireFromDocs = createRequire(path.join(REPO_ROOT, "apps/docs/package.json"));
  const sharp = requireFromDocs("sharp") as typeof import("sharp");
  const lockup = await sharp(await readKit("svg/mate-horizontal-on-dark.svg"), { density: 300 })
    .resize({ width: 760 })
    .png()
    .toBuffer();
  await sharp({
    create: { width: 1200, height: 630, channels: 4, background: BRAND_COLORS.night.hex },
  })
    .composite([{ input: lockup, gravity: "center" }])
    .png()
    .toFile(path.join(REPO_ROOT, OG_IMAGE));
}

async function writeOutputs(): Promise<void> {
  for (const output of await brandOutputs()) {
    const target = path.join(REPO_ROOT, output.path);
    await fs.mkdir(path.dirname(target), { recursive: true });
    await fs.writeFile(target, output.content);
  }
  await renderOgImage();
}

if (import.meta.main) {
  if (process.argv.includes("--check")) {
    const problems = await checkBrand();
    if (problems.length > 0) {
      console.error(
        `The brand is inconsistent (run \`bun run brand:generate\` for stale outputs):\n${problems.map((p) => `  ${p}`).join("\n")}`,
      );
      process.exit(1);
    }
    console.log("Brand outputs, palette, and sources match assets/logo-kit.");
  } else {
    await writeOutputs();
    console.log("Brand outputs written from assets/logo-kit.");
  }
}
