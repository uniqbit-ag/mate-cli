#!/usr/bin/env bun
/**
 * Bundles Studio's typed client modules into one script and writes it as a source module, so the
 * published package, which ships `src/` and has no build of its own, serves it without a file read.
 *
 *   bun scripts/studio-client/build.ts           write studio-client.generated.ts
 *   bun scripts/studio-client/build.ts --check   exit 1 when the committed module is out of date
 */
import fs from "node:fs/promises";
import path from "node:path";

const REPO_ROOT = path.resolve(import.meta.dirname, "..", "..");
const VIEWS = path.join(REPO_ROOT, "packages/mate-core/src/cli/commands/studio/views");

const ENTRY = path.join(VIEWS, "studio-client/main.ts");
export const GENERATED_MODULE = path.join(VIEWS, "studio-client.generated.ts");

const HEADER =
  "// Generated by scripts/studio-client/build.ts from views/studio-client. Do not edit.";

/** The bundled client, unminified so the served script stays readable and the check stays stable. */
export async function bundleStudioClient(): Promise<string> {
  const result = await Bun.build({
    entrypoints: [ENTRY],
    target: "browser",
    format: "iife",
    minify: false,
    sourcemap: "none",
  });
  if (!result.success) {
    throw new Error(`Studio client build failed:\n${result.logs.map(String).join("\n")}`);
  }
  const [output] = result.outputs;
  if (!output || result.outputs.length !== 1) {
    throw new Error("Studio client build must produce exactly one script");
  }
  return withRepoRelativeComments(await output.text());
}

/** Bun labels each module with a path relative to the cwd; pin it to the repository root instead. */
function withRepoRelativeComments(script: string): string {
  return script.replace(/^( *\/\/ )(\S+\.ts)$/gm, (_line, lead: string, source: string) => {
    return `${lead}${path.relative(REPO_ROOT, path.resolve(process.cwd(), source))}`;
  });
}

/** The generated module's text for a bundled script. */
export function generatedModule(script: string): string {
  return `${HEADER}\nexport const STUDIO_CLIENT_BUNDLE = ${JSON.stringify(script)};\n`;
}

/** Empty when the committed module matches a fresh build; otherwise says what to run. */
export async function checkStudioClient(): Promise<string[]> {
  const expected = generatedModule(await bundleStudioClient());
  const actual = await fs.readFile(GENERATED_MODULE, "utf8").catch(() => null);
  return actual === expected
    ? []
    : [`${path.relative(REPO_ROOT, GENERATED_MODULE)} is out of date: run bun scripts/studio-client/build.ts`];
}

if (import.meta.main) {
  if (process.argv.includes("--check")) {
    const problems = await checkStudioClient();
    for (const problem of problems) console.error(problem);
    process.exit(problems.length === 0 ? 0 : 1);
  }
  await fs.writeFile(GENERATED_MODULE, generatedModule(await bundleStudioClient()));
  console.log(`wrote ${path.relative(REPO_ROOT, GENERATED_MODULE)}`);
}
